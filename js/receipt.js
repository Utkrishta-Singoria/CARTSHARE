(function () {
  'use strict';

  var CS = window.CartShare;
  var esc = CS.escapeHtml;

  var session = CS.getSession();
  var room = session ? CS.getRoom(session.code) : null;
  if (!session || !room) {
    window.location.replace('index.html');
    return;
  }

  var code = room.code;
  var paper = document.getElementById('receipt');
  var generatedAt = new Date();

  function pad(n) { return String(n).padStart(2, '0'); }

  function stamp(d) {
    return d.getFullYear() + pad(d.getMonth() + 1) + pad(d.getDate()) + '-' + pad(d.getHours()) + pad(d.getMinutes());
  }

  function fmtDate(ts) {
    return new Date(ts).toLocaleString([], {
      year: 'numeric', month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit'
    });
  }

  function summary(r) {
    var total = CS.roomTotal(r);
    return {
      total: total,
      unlocked: total >= r.threshold,
      gap: Math.max(0, r.threshold - total),
      people: CS.totalsByMember(r).filter(function (p) { return p.total > 0 || p.count > 0; })
    };
  }

  /* ---------- HTML receipt ---------- */

  function render() {
    var r = CS.getRoom(code);
    if (!r) { window.location.replace('index.html'); return; }
    room = r;

    var s = summary(r);
    var money = function (n) { return esc(CS.formatMoney(n, r.currency)); };
    var receiptNo = code + '-' + stamp(generatedAt);

    var rows = r.items.length
      ? r.items.map(function (it) {
          return '<tr><td>' + esc(it.name) + '<div class="sub">added by ' + esc(it.addedBy) + '</div></td>' +
            '<td class="num">' + it.qty + '</td>' +
            '<td class="num">' + money(it.price) + '</td>' +
            '<td class="num">' + money(CS.lineTotal(it)) + '</td></tr>';
        }).join('')
      : '<tr><td colspan="4" class="center">No items in the cart.</td></tr>';

    var split = s.people.length
      ? s.people.map(function (p) {
          return '<tr><td>' + esc(p.name) + '</td><td class="num">' + p.count + ' pcs</td><td class="num">' + money(p.total) + '</td></tr>';
        }).join('')
      : '<tr><td colspan="3" class="center">Nothing to split yet.</td></tr>';

    var audit = r.log.length
      ? r.log.map(function (e) {
          return '<tr><td>' + esc(fmtDate(e.t)) + '</td><td>' + esc(e.who) + ' ' + esc(e.text) + '</td></tr>';
        }).join('')
      : '<tr><td colspan="2" class="center">No activity recorded.</td></tr>';

    paper.innerHTML =
      '<header>' +
        '<h1>CartShare</h1>' +
        '<p class="center mb-0">Group order receipt</p>' +
      '</header>' +
      '<hr>' +
      '<section>' +
        '<table><tbody>' +
          '<tr><td>Receipt no.</td><td class="num">' + esc(receiptNo) + '</td></tr>' +
          '<tr><td>Room</td><td class="num">' + esc(code) + '</td></tr>' +
          '<tr><td>Created by</td><td class="num">' + esc(r.createdBy) + '</td></tr>' +
          '<tr><td>Members</td><td class="num">' + Object.keys(r.members).length + '</td></tr>' +
          '<tr><td>Printed</td><td class="num">' + esc(fmtDate(generatedAt.getTime())) + '</td></tr>' +
        '</tbody></table>' +
      '</section>' +
      '<hr>' +
      '<section>' +
        '<table>' +
          '<thead><tr><th>Item</th><th class="num">Qty</th><th class="num">Each</th><th class="num">Total</th></tr></thead>' +
          '<tbody>' + rows + '</tbody>' +
          '<tfoot><tr class="total-row"><td colspan="3">Total</td><td class="num">' + money(s.total) + '</td></tr></tfoot>' +
        '</table>' +
      '</section>' +
      '<hr>' +
      '<section>' +
        '<table><tbody>' +
          '<tr><td>Free delivery goal</td><td class="num">' + money(r.threshold) + '</td></tr>' +
          '<tr><td>Status</td><td class="num">' + (s.unlocked ? 'Unlocked' : 'Short by ' + money(s.gap)) + '</td></tr>' +
        '</tbody></table>' +
      '</section>' +
      '<hr>' +
      '<section>' +
        '<h2>Split by person</h2>' +
        '<table><thead><tr><th>Name</th><th class="num">Items</th><th class="num">Owes</th></tr></thead>' +
        '<tbody>' + split + '</tbody></table>' +
      '</section>' +
      '<hr>' +
      '<section>' +
        '<h2>Audit trail</h2>' +
        '<table><thead><tr><th>When</th><th>What happened</th></tr></thead>' +
        '<tbody>' + audit + '</tbody></table>' +
      '</section>' +
      '<hr>' +
      '<p class="center sub mb-0">Generated by CartShare</p>';

    document.title = 'CartShare_' + code + '_receipt';
  }

  /* ---------- plain-text version ---------- */

  function line(left, right, width) {
    var gap = Math.max(1, width - left.length - right.length);
    return left + new Array(gap + 1).join(' ') + right;
  }

  function buildText() {
    var r = room;
    var s = summary(r);
    var W = 42;
    var fm = function (n) { return CS.formatMoney(n, r.currency); };
    var out = [];
    out.push('CARTSHARE GROUP ORDER');
    out.push('Room ' + code + ' | ' + fmtDate(generatedAt.getTime()));
    out.push(new Array(W + 1).join('-'));
    if (!r.items.length) out.push('No items in the cart.');
    r.items.forEach(function (it) {
      out.push(line(it.qty + ' x ' + it.name, fm(CS.lineTotal(it)), W));
      out.push('   ' + fm(it.price) + ' each, added by ' + it.addedBy);
    });
    out.push(new Array(W + 1).join('-'));
    out.push(line('TOTAL', fm(s.total), W));
    out.push(line('Free delivery goal', fm(r.threshold), W));
    out.push(line('Status', s.unlocked ? 'Unlocked' : 'Short by ' + fm(s.gap), W));
    out.push('');
    out.push('SPLIT BY PERSON');
    s.people.forEach(function (p) { out.push(line(p.name, fm(p.total), W)); });
    return out.join('\n');
  }

  /* ---------- buttons ---------- */

  function toast(message) {
    document.getElementById('toastBody').textContent = message;
    if (window.bootstrap) bootstrap.Toast.getOrCreateInstance(document.getElementById('appToast'), { delay: 2400 }).show();
  }

  document.getElementById('printBtn').addEventListener('click', function () {
    render();
    window.print();
  });

  document.getElementById('copyTextBtn').addEventListener('click', function () {
    var text = buildText();
    if (navigator.clipboard && navigator.clipboard.writeText) {
      navigator.clipboard.writeText(text).then(
        function () { toast('Receipt copied as text'); },
        function () { window.prompt('Copy the receipt text:', text); }
      );
    } else {
      window.prompt('Copy the receipt text:', text);
    }
  });

  // Keep the receipt in step with the room while it is open in another tab
  window.addEventListener('storage', function (e) {
    if (e.key === null || e.key === CS.ROOMS_KEY) render();
  });

  render();
})();
